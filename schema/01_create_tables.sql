-- 1. STATIONS
CREATE TABLE stations (
    station_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    latitude DECIMAL(10,7),
    longitude DECIMAL(10,7),
    capacity INTEGER
);

-- 2. USERS
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giu_id VARCHAR(20) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. GEOFENCES
CREATE TABLE geofences (
    geofence_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    boundary_coordinates TEXT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE
);

-- 4. BIKES
CREATE TABLE bikes (
    bike_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(100),
    type VARCHAR(50),
    status VARCHAR(20) NOT NULL,
    station_id INTEGER,
    FOREIGN KEY (station_id) REFERENCES stations(station_id)
        ON DELETE SET NULL
);

-- 5. PAYMENT METHODS
CREATE TABLE payment_methods (
    payment_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    provider_token TEXT NOT NULL,
    card_brand VARCHAR(30),
    last_four_digits CHAR(4),
    expiry_month INTEGER,
    expiry_year INTEGER,
    is_default BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);

-- 6. RENTALS
CREATE TABLE rentals (
    rental_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    bike_id INTEGER NOT NULL,
    start_station_id INTEGER,
    end_station_id INTEGER,
    start_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    end_time TIMESTAMP,
    distance DECIMAL(10,2),
    total_cost DECIMAL(10,2),
    status VARCHAR(20) NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(user_id),
    FOREIGN KEY (bike_id) REFERENCES bikes(bike_id),
    FOREIGN KEY (start_station_id) REFERENCES stations(station_id)
        ON DELETE SET NULL,
    FOREIGN KEY (end_station_id) REFERENCES stations(station_id)
        ON DELETE SET NULL
);

-- 7. PAYMENTS
CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id INTEGER NOT NULL,
    payment_method_id INTEGER NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    payment_status VARCHAR(20) NOT NULL,
    transaction_reference VARCHAR(255),
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (rental_id) REFERENCES rentals(rental_id),
    FOREIGN KEY (payment_method_id)
        REFERENCES payment_methods(payment_method_id)
);

-- 8. BIKE LOCATIONS
CREATE TABLE bike_locations (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id INTEGER NOT NULL,
    rental_id INTEGER,
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (bike_id) REFERENCES bikes(bike_id),
    FOREIGN KEY (rental_id) REFERENCES rentals(rental_id)
        ON DELETE SET NULL
);

-- 9. BIKE PROBLEMS
CREATE TABLE bike_problems (
    problem_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    description TEXT NOT NULL,
    reported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    FOREIGN KEY (bike_id) REFERENCES bikes(bike_id),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);

-- 10. SUPPORT TICKETS
CREATE TABLE support_tickets (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    subject VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);